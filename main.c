void imprimirPantalla(Chip8 *cpu){
    for(int i = 0; i < 32; i++){
        for (int j = 0; j < 8; j++){
            for (int bit = 7; bit >= 0; bit--){
                uint8_t pixel = (cpu->pantalla[i][j] >> bit) & 1;
                putchar(pixel ? '#' : ' ');
            }
        }
        putchar('\n');
    }
}

